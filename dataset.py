import numpy as np
from sklearn.model_selection import StratifiedShuffleSplit
from pathlib import Path

import nibabel as nib
import pandas as pd



def create_cases_dataframe(df, nifti_dir):
    """
    Create a list of cases from the dataset dataframe.

    Each case contains the path to the corresponding NIfTI image,
    its binary classification label, and its unique identifier.

    Parameters
    ----------
    df : pandas.DataFrame
        Dataframe containing the dataset metadata.
        It must contain the following columns:
        - "uid": unique identifier of each scan.
        - "is_pathologic": binary target label (0 or 1).

    nifti_dir : pathlib.Path
        Directory containing the NIfTI files.
        Each file is expected to be named "<uid>.nii.gz".

    Returns
    -------
    list of dict
        List of cases. Each case is represented as a dictionary
        containing:
        - "image": path to the NIfTI file.
        - "label": binary classification label.
        - "uid": unique identifier of the scan.
    """

    cases = []

    for _, row in df.iterrows():

        uid = row["uid"]

        cases.append({
            "image": str(nifti_dir / f"{uid}.nii.gz"),
            "label": float(row["is_pathologic"]),
            "uid": uid
        })

    return cases


def create_train_val_indices(cases):
    """
    Split cases into stratified training and validation sets.

    The split preserves approximately the same class distribution
    between the training and validation sets.

    Parameters
    ----------
    cases : list of dict
        List of cases generated by `create_cases_dataframe`.
        Each case must contain a "label" key with the binary
        classification label.

    Returns
    -------
    tuple of list
        A tuple containing:
        - train_cases: cases assigned to the training set.
        - val_cases: cases assigned to the validation set.

    Notes
    -----
    The validation set contains 20% of the cases.

    Stratification is performed using the case labels and the
    random seed defined by the global variable `SEED`.
    """

    labels = np.array([c["label"] for c in cases])

    indices = np.arange(len(cases))

    splitter = StratifiedShuffleSplit(
        n_splits=1,
        test_size=0.2,
        random_state=SEED
    )

    train_idx, val_idx = next(splitter.split(indices, labels))

    train_cases = [cases[i] for i in train_idx]

    val_cases = [cases[i] for i in val_idx]

    return train_cases, val_cases



